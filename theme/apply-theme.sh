#!/usr/bin/env bash
set -euo pipefail

config_home="${XDG_CONFIG_HOME:-$HOME/.config}"
theme_dir="$config_home/theme"
palette_file="$theme_dir/palette.json"
mode_file="$theme_dir/mode"
generation_file="$theme_dir/generation"
requested="${1:-current}"

# Serialize palette changes with normal dark/light theme switches.
exec 9> "$theme_dir/.apply.lock"
flock -x 9

current_mode="dark"
if [[ -r "$mode_file" ]]; then
    read -r current_mode < "$mode_file" || current_mode="dark"
fi
[[ "$current_mode" == "light" ]] || current_mode="dark"

case "$requested" in
    dark|light) mode="$requested" ;;
    toggle)
        if [[ "$current_mode" == "dark" ]]; then mode="light"; else mode="dark"; fi
        ;;
    current) mode="$current_mode" ;;
    color)
        mode="$current_mode"
        python3 "$theme_dir/theme-color.py" set "${2:-}" "$mode"
        ;;
    *)
        printf 'Usage: %s [dark|light|toggle|current|color HEX|color --reset]\n' "$0" >&2
        exit 2
        ;;
esac

color() {
    jq -er --arg mode "$mode" --arg key "$1" '.[$mode][$key]' "$palette_file"
}

bg=$(color bg); bg1=$(color bg1); bg2=$(color bg2); bg3=$(color bg3)
fg=$(color fg); fg2=$(color fg2); fg3=$(color fg3)
accent=$(color accent); red=$(color red); teal=$(color teal); orange=$(color orange)
blue=$(color blue); green=$(color green); yellow=$(color yellow); purple=$(color purple)
selection=$(color sel); search=$(color search)

if [[ "$mode" == "dark" ]]; then
    icon_theme="Papirus-Dark"
    toolkit_theme="Breeze-Dark"
    prefer_dark="true"
    system_scheme="prefer-dark"
    kitty_background_image="$config_home/kitty/grid-current.png"
else
    icon_theme="Papirus-Light"
    toolkit_theme="Breeze"
    prefer_dark="false"
    system_scheme="default"
    kitty_background_image="none"
fi

hex_rgb() {
    local hex="${1#\#}"
    printf '%d,%d,%d' "$((16#${hex:0:2}))" "$((16#${hex:2:2}))" "$((16#${hex:4:2}))"
}

argb() {
    printf '#ff%s' "${1#\#}"
}

replace_setting() {
    local file="$1" key="$2" value="$3"
    [[ -f "$file" ]] || return 0
    if grep -q "^${key}=" "$file"; then
        sed -i -E "s|^${key}=.*|${key}=${value}|" "$file"
    else
        printf '%s=%s\n' "$key" "$value" >> "$file"
    fi
}

# Shared state and compositor adapters.
cat > "$theme_dir/current.lua" <<EOF
-- Generated by apply-theme.sh. Do not edit directly.
return {
    mode = "$mode",
    bg = "rgb(${bg#\#})",
    bg2 = "rgb(${bg2#\#})",
    fg = "rgb(${fg#\#})",
    accent = "rgb(${accent#\#})",
    accent_rgba = "rgba(${accent#\#}ff)",
}
EOF

cat > "$theme_dir/hyprland.conf" <<EOF
\$theme_bg = rgb(${bg#\#})
\$theme_bg2 = rgb(${bg2#\#})
\$theme_fg = rgb(${fg#\#})
\$theme_accent = rgb(${accent#\#})
\$theme_teal = rgb(${teal#\#})
\$theme_error = rgb(${red#\#})
EOF

cat > "$theme_dir/hyprlock.conf" <<EOF
\$theme_bg = rgba(${bg#\#}ee)
\$theme_bg_opaque = rgba(${bg#\#}ff)
\$theme_fg = rgba(${fg#\#}ff)
\$theme_fg2 = rgba(${fg2#\#}ff)
\$theme_muted = rgba(${fg3#\#}aa)
\$theme_accent = rgba(${accent#\#}ff)
\$theme_blue = rgba(${blue#\#}ff)
EOF

# Terminal palettes. Kitty's background pattern stays exclusive to dark mode.
cat > "$theme_dir/kitty.conf" <<EOF
foreground $fg2
background $bg
selection_foreground $fg
selection_background $selection
cursor $accent
cursor_text_color $bg
url_color $blue
active_border_color $accent
inactive_border_color $bg3
active_tab_foreground $accent
active_tab_background $bg
inactive_tab_foreground $fg3
inactive_tab_background $bg
color0 $bg2
color1 $red
color2 $green
color3 $yellow
color4 $blue
color5 $purple
color6 $teal
color7 $fg2
color8 $fg3
color9 $red
color10 $green
color11 $yellow
color12 $blue
color13 $purple
color14 $teal
color15 $fg
background_image $kitty_background_image
EOF

# Generate interactive terminal surfaces with the same rules as Neovim.
python3 "$theme_dir/theme-color.py" alacritty "$mode"

# GTK CSS consumers: Waybar, Wofi, SwayNC and Wlogout all import this file.
cat > "$theme_dir/colors.css" <<EOF
@define-color theme_bg $bg;
@define-color theme_bg1 $bg1;
@define-color theme_bg2 $bg2;
@define-color theme_bg3 $bg3;
@define-color theme_fg $fg;
@define-color theme_fg2 $fg2;
@define-color theme_muted $fg3;
@define-color theme_accent $accent;
@define-color theme_red $red;
@define-color theme_teal $teal;
@define-color theme_orange $orange;
@define-color theme_blue $blue;
@define-color theme_green $green;
@define-color theme_yellow $yellow;
@define-color theme_purple $purple;
@define-color theme_selection $selection;
@define-color theme_search $search;
EOF

# Rebuild the Breeze variable table used by GTK 3/4 while preserving its keys.
generate_gtk_colors() {
    local source="$1" target="$2" line name value
    : > "$target"
    while IFS= read -r line; do
        if [[ "$line" =~ ^@define-color[[:space:]]+([^[:space:]]+) ]]; then
            name="${BASH_REMATCH[1]}"
            case "$name" in
                *error*) value="$red" ;;
                *warning*) value="$orange" ;;
                *success*) value="$green" ;;
                *link_visited*) value="$purple" ;;
                *link*) value="$blue" ;;
                *selected_fg*) value="$bg" ;;
                *selected_bg*|*decoration*|*hovering_selected*) value="$accent" ;;
                *base*|*view_bg*) value="$bg" ;;
                *button_background*|*tooltip_background*|*titlebar_background*) value="$bg2" ;;
                *header_background*|*bg_color*|*background*) value="$bg1" ;;
                *border*|*outline*) value="$bg3" ;;
                *insensitive*|*unfocused*|*backdrop*) value="$fg3" ;;
                *foreground*|*text*) value="$fg" ;;
                *) value="$fg2" ;;
            esac
            printf '@define-color %s %s;\n' "$name" "$value" >> "$target"
        else
            printf '%s\n' "$line" >> "$target"
        fi
    done < "$source"
}

gtk_template="$config_home/gtk-3.0/colors.css"
gtk_temp=$(mktemp)
generate_gtk_colors "$gtk_template" "$gtk_temp"
install -m 0644 "$gtk_temp" "$config_home/gtk-3.0/colors.css"
install -m 0644 "$gtk_temp" "$config_home/gtk-4.0/colors.css"
rm -f "$gtk_temp"

for settings in "$config_home/gtk-3.0/settings.ini" "$config_home/gtk-4.0/settings.ini"; do
    replace_setting "$settings" gtk-application-prefer-dark-theme "$prefer_dark"
    replace_setting "$settings" gtk-icon-theme-name "$icon_theme"
    replace_setting "$settings" gtk-theme-name "$toolkit_theme"
done

if [[ -f "$config_home/gtkrc" ]]; then
    sed -i -E "s|^include \"/usr/share/themes/[^/]+/gtk-2.0/gtkrc\"|include \"/usr/share/themes/$toolkit_theme/gtk-2.0/gtkrc\"|" "$config_home/gtkrc"
    sed -i -E "s|^gtk-theme-name=.*|gtk-theme-name=\"$toolkit_theme\"|" "$config_home/gtkrc"
fi
if [[ -f "$config_home/xsettingsd/xsettingsd.conf" ]]; then
    sed -i -E \
        -e "s|^Net/IconThemeName .*|Net/IconThemeName \"$icon_theme\"|" \
        -e "s|^Net/ThemeName .*|Net/ThemeName \"$toolkit_theme\"|" \
        "$config_home/xsettingsd/xsettingsd.conf"
fi

# Qt5ct palette. Qt applications inherit the same surfaces and semantic colors.
qt_palette="$config_home/qt5ct/colors/global-theme.conf"
mkdir -p "$(dirname "$qt_palette")"
active_colors="$(argb "$fg2"), $(argb "$bg2"), $(argb "$bg3"), $(argb "$bg2"), $(argb "$bg"), $(argb "$bg1"), $(argb "$fg"), $(argb "$accent"), $(argb "$fg"), $(argb "$bg"), $(argb "$bg1"), #ff000000, $(argb "$accent"), $(argb "$bg"), $(argb "$blue"), $(argb "$purple"), $(argb "$bg1"), #ff000000, $(argb "$bg2"), $(argb "$fg"), $(argb "$fg3")"
disabled_colors="$(argb "$fg3"), $(argb "$bg2"), $(argb "$bg3"), $(argb "$bg2"), $(argb "$bg"), $(argb "$bg1"), $(argb "$fg3"), $(argb "$fg3"), $(argb "$fg3"), $(argb "$bg"), $(argb "$bg1"), #ff000000, $(argb "$bg3"), $(argb "$fg3"), $(argb "$fg3"), $(argb "$purple"), $(argb "$bg1"), #ff000000, $(argb "$bg2"), $(argb "$fg3"), $(argb "$fg3")"
cat > "$qt_palette" <<EOF
[ColorScheme]
active_colors=$active_colors
disabled_colors=$disabled_colors
inactive_colors=$active_colors
EOF
qt5ct_conf="$config_home/qt5ct/qt5ct.conf"
replace_setting "$qt5ct_conf" color_scheme_path "$qt_palette"
replace_setting "$qt5ct_conf" icon_theme "$icon_theme"

# KDE/Qt6 applications read this color scheme even outside Plasma.
kde_scheme_dir="$HOME/.local/share/color-schemes"
mkdir -p "$kde_scheme_dir"
cat > "$kde_scheme_dir/Global.colors" <<EOF
[General]
Name=Global
ColorScheme=Global

[Colors:Button]
BackgroundNormal=$(hex_rgb "$bg2")
ForegroundNormal=$(hex_rgb "$fg2")
DecorationFocus=$(hex_rgb "$accent")
DecorationHover=$(hex_rgb "$accent")
ForegroundNegative=$(hex_rgb "$red")
ForegroundNeutral=$(hex_rgb "$orange")
ForegroundPositive=$(hex_rgb "$green")

[Colors:Selection]
BackgroundNormal=$(hex_rgb "$accent")
ForegroundNormal=$(hex_rgb "$bg")
DecorationFocus=$(hex_rgb "$accent")
DecorationHover=$(hex_rgb "$accent")

[Colors:Tooltip]
BackgroundNormal=$(hex_rgb "$bg2")
ForegroundNormal=$(hex_rgb "$fg")

[Colors:View]
BackgroundAlternate=$(hex_rgb "$bg1")
BackgroundNormal=$(hex_rgb "$bg")
ForegroundInactive=$(hex_rgb "$fg3")
ForegroundNormal=$(hex_rgb "$fg2")
DecorationFocus=$(hex_rgb "$accent")
DecorationHover=$(hex_rgb "$accent")

[Colors:Window]
BackgroundAlternate=$(hex_rgb "$bg2")
BackgroundNormal=$(hex_rgb "$bg1")
ForegroundInactive=$(hex_rgb "$fg3")
ForegroundNormal=$(hex_rgb "$fg2")
DecorationFocus=$(hex_rgb "$accent")
DecorationHover=$(hex_rgb "$accent")

[WM]
activeBackground=$(hex_rgb "$bg2")
activeForeground=$(hex_rgb "$fg")
inactiveBackground=$(hex_rgb "$bg1")
inactiveForeground=$(hex_rgb "$fg3")
EOF

# Shell prompt and fish inherit the same mode immediately in new shells.
cat > "$config_home/fish/conf.d/theme.fish" <<EOF
set -gx SYSTEM_THEME_MODE $mode
set -g fish_color_normal ${fg2#\#}
set -g fish_color_command ${fg#\#}
set -g fish_color_keyword ${accent#\#}
set -g fish_color_quote ${teal#\#}
set -g fish_color_redirection ${accent#\#}
set -g fish_color_end ${accent#\#}
set -g fish_color_error ${red#\#}
set -g fish_color_param ${fg2#\#}
set -g fish_color_comment ${fg3#\#}
set -g fish_color_match --background=${selection#\#}
set -g fish_color_selection --background=${selection#\#}
set -g fish_color_operator ${accent#\#}
set -g fish_color_escape ${orange#\#}
set -g fish_color_autosuggestion ${fg3#\#}
set -g fish_color_cwd ${accent#\#}
set -g fish_color_cwd_root ${red#\#}
set -g fish_pager_color_prefix ${accent#\#}
set -g fish_pager_color_completion ${fg2#\#}
set -g fish_pager_color_description ${fg3#\#}
EOF

starship_conf="$config_home/starship.toml"
sed -i -E \
    -e "s|^(bg = ).*|\1\"$bg\"|" \
    -e "s|^(surface = ).*|\1\"$bg2\"|" \
    -e "s|^(fg = ).*|\1\"$fg\"|" \
    -e "s|^(muted = ).*|\1\"$fg3\"|" \
    -e "s|^(accent = ).*|\1\"$accent\"|" \
    "$starship_conf"

# Quickshell/Material adapter.
quickshell_colors="$config_home/quickshell/nucleus-shell/config/colors.json"
if [[ -d "$(dirname "$quickshell_colors")" ]]; then
    jq --arg mode "$mode" '.[$mode] | {
      background:.bg, surface:.bg, surface_dim:.bg, surface_container:.bg2,
      surface_container_low:.bg1, surface_container_high:.bg2,
      surface_container_highest:.bg3, on_background:.fg, on_surface:.fg,
      on_surface_variant:.fg2, outline:.fg3, outline_variant:.bg3,
      primary:.accent, on_primary:.bg, primary_container:.sel,
      on_primary_container:.fg, secondary:.teal, tertiary:.purple,
      error:.red, source_color:.accent, surface_tint:.accent,
      scrim:"#000000", shadow:"#000000"
    }' "$palette_file" > "$quickshell_colors"
fi

# Notifications and lock screen.
dunst_conf="$config_home/dunst/dunstrc"
if [[ -f "$dunst_conf" ]]; then
    sed -i -E \
      -e "s|^([[:space:]]*background = )\"#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?\"|\1\"${bg}f2\"|" \
      -e "s|^([[:space:]]*foreground = )\"#[0-9a-fA-F]{6}\"|\1\"$fg2\"|" \
      -e "/^\[urgency_low\]/,/^\[urgency_normal\]/ s|^([[:space:]]*frame_color = ).*|\1\"$bg3\"|" \
      -e "/^\[urgency_normal\]/,/^\[urgency_critical\]/ s|^([[:space:]]*frame_color = ).*|\1\"$bg3\"|" \
      -e "/^\[urgency_critical\]/,\$ s|^([[:space:]]*frame_color = ).*|\1\"$accent\"|" \
      -e "s|(foreground=')[^']+('>&gt;)|\1$accent\2|" \
      -e "s|(foreground=')[^']+('><b>!</b>)|\1$red\2|" \
      -e "s|(foreground=')[^']+('>·)|\1$fg3\2|" \
      "$dunst_conf"
fi

# Firefox chrome/content variables; webpages retain their own intended colors.
for firefox_profile in "$config_home"/mozilla/firefox/*.default-release; do
    [[ -d "$firefox_profile/chrome" ]] || continue
    cat > "$firefox_profile/chrome/theme.css" <<EOF
:root {
  color-scheme: $mode;
  --tui-bg: $bg; --tui-bg-2: $bg2; --tui-bg-3: $bg3;
  --tui-fg: $fg; --tui-fg-2: $fg2; --tui-muted: $fg3;
  --tui-accent: $accent; --tui-error: $red; --tui-ok: $green; --tui-warn: $yellow;
}
EOF
    user_js="$firefox_profile/user.js"
    [[ -f "$user_js" ]] || continue
    sed -i -E \
      -e "s|^(user_pref\(\"browser\.display\.background_color\", )[[:space:]]*\"#[0-9a-fA-F]{6}\"\);|\1\"$bg\"\);|" \
      -e "s|^(user_pref\(\"browser\.display\.background_color\.dark\", )[[:space:]]*\"#[0-9a-fA-F]{6}\"\);|\1\"$bg\"\);|" \
      "$user_js"
done

# Recolor standalone TUI themes without replacing their layout/behavior.
recolor_file() {
    local file="$1"
    [[ -f "$file" ]] || return 0
    sed -i -E \
      -e "s~#(f2f2f2|f5f5f5|ffffff|1f1e1c)~$fg~gI" \
      -e "s~#(d0d0d0|d3d3d3|c9c9c9|eeeeee|484541)~$fg2~gI" \
      -e "s~#(888888|808080|747474|77716a)~$fg3~gI" \
      -e "s~#(ff2028|ff4444|ff4d4d|ff5c5c|c43c3c)~$accent~gI" \
      -e "s~#(b8b8b8|44bbbb|367a76)~$teal~gI" \
      -e "s~#(d76a6a|ff7722|b55d2b)~$orange~gI" \
      -e "s~#(22aaee|326b91)~$blue~gI" \
      -e "s~#(44dd44|527a3e)~$green~gI" \
      -e "s~#(ffdd44|946816)~$yellow~gI" \
      -e "s~#(9b7b7b|dd88ff|76558d)~$purple~gI" \
      -e "s~#(4a1f1f|e8cbc7)~$selection~gI" \
      "$file"
}

recolor_file "$config_home/yazi/theme.toml"
recolor_file "$config_home/yazi/init.lua"
if [[ -f "$config_home/yazi/theme.toml" ]]; then
    sed -i -E \
      -e "s|bg = \"$accent\"|bg = \"$selection\"|g" \
      -e "/^(marker_cut|marker_selected|btn_yes)[[:space:]]*=/ s|bg = \"$selection\"|bg = \"$accent\"|" \
      "$config_home/yazi/theme.toml"
fi
recolor_file "$config_home/cava/config"
recolor_file "$config_home/silicon/themes/obsidian-ember.tmTheme"
recolor_file "$config_home/wofi/hex-grid.svg"

zathura_conf="$config_home/zathura/zathurarc"
if [[ -f "$zathura_conf" ]]; then
    recolor_file "$zathura_conf"
    sed -i -E \
      -e "s|^(set highlight-color[[:space:]]+).*|\1\"${accent}44\"|" \
      -e "s|^(set highlight-active-color[[:space:]]+).*|\1\"${accent}aa\"|" \
      -e "s|^(set recolor-lightcolor[[:space:]]+).*|\1\"$bg\"|" \
      -e "s|^(set recolor-darkcolor[[:space:]]+).*|\1\"$fg2\"|" \
      "$zathura_conf"
fi

# Spotatui uses RGB triples and otherwise inherits terminal foreground/background.
spotatui_conf="$config_home/spotatui/config.yml"
if [[ -f "$spotatui_conf" ]]; then
    accent_rgb=$(hex_rgb "$accent"); red_rgb=$(hex_rgb "$red")
    teal_rgb=$(hex_rgb "$teal"); yellow_rgb=$(hex_rgb "$yellow"); muted_rgb=$(hex_rgb "$fg3")
    sed -i -E \
      -e "s~^([[:space:]]*(active|banner|hovered|playbar_progress|selected):).*~\1 $accent_rgb~" \
      -e "s~^([[:space:]]*(error_border|error_text):).*~\1 $red_rgb~" \
      -e "s~^([[:space:]]*hint:).*~\1 $yellow_rgb~" \
      -e "s~^([[:space:]]*inactive:).*~\1 $muted_rgb~" \
      -e "s~^([[:space:]]*highlighted_lyrics:).*~\1 $teal_rgb~" \
      "$spotatui_conf"
fi

# Named surface adapters handle repeated custom colors without matching old hexes.
python3 "$theme_dir/theme-color.py" render "$mode"

# Publish a new generation before the mode. Neovim watches the mode file, so
# this order guarantees that a global apply permanently invalidates any local
# per-window overrides, even after cycling back to the same mode later.
printf '%s-%s-%s\n' "$(date +%s%N)" "$$" "$RANDOM" > "$generation_file"
printf '%s\n' "$mode" > "$mode_file"

if [[ "${THEME_NO_RELOAD:-0}" != "1" ]]; then
    command -v gsettings >/dev/null && gsettings set org.gnome.desktop.interface color-scheme "$system_scheme" >/dev/null 2>&1 || true
    command -v gsettings >/dev/null && gsettings set org.gnome.desktop.interface gtk-theme "$toolkit_theme" >/dev/null 2>&1 || true
    command -v gsettings >/dev/null && gsettings set org.gnome.desktop.interface icon-theme "$icon_theme" >/dev/null 2>&1 || true
    command -v kwriteconfig6 >/dev/null && kwriteconfig6 --file kdeglobals --group General --key ColorScheme Global >/dev/null 2>&1 || true
    command -v kwriteconfig6 >/dev/null && kwriteconfig6 --file kdeglobals --group Icons --key Theme "$icon_theme" >/dev/null 2>&1 || true
    hyprctl reload >/dev/null 2>&1 || true
    if pgrep -x waybar >/dev/null; then pkill -SIGUSR2 waybar || true; fi
    if pgrep -x kitty >/dev/null; then pkill -SIGUSR1 kitty || true; fi
    dunstctl reload >/dev/null 2>&1 || true
    if command -v swaync-client >/dev/null; then swaync-client --reload-css >/dev/null 2>&1 || true; fi

    notify-send -a Theme -i preferences-desktop-theme "System theme" "Switched to $mode mode" >/dev/null 2>&1 || true
fi

printf 'Applied %s theme, background %s, from %s\n' "$mode" "$bg" "$palette_file"
