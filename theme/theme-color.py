#!/usr/bin/env python3
"""Persistent background colors and adapters for the existing theme generator."""

import configparser
import json
import os
from pathlib import Path
import re
import sys
import tempfile

CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config")))
THEME = CONFIG / "theme"


def write(path, text):
    """Replace complete files atomically, retaining their permissions."""
    path = path.resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(text)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def current_mode():
    path = THEME / "mode"
    return "light" if path.exists() and path.read_text().strip() == "light" else "dark"


def rgb(value):
    return tuple(int(value[i:i + 2], 16) for i in (1, 3, 5))


def luminance(value):
    channels = [channel / 255 for channel in rgb(value)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
              for c in channels]
    return sum(c * weight for c, weight in zip(linear, (0.2126, 0.7152, 0.0722)))


def readable_on(background):
    return "#000000" if luminance(background) > 0.179 else "#ffffff"


def mix(background, foreground, amount):
    # Match Neovim's rounding and surface strengths in theme/palette.lua.
    channels = [int(bg + (fg - bg) * amount + 0.5)
                for bg, fg in zip(rgb(background), rgb(foreground))]
    return "#" + "".join(f"{channel:02x}" for channel in channels)


def interaction_colors(background):
    contrast = readable_on(background)
    colors = {key: mix(background, contrast, amount) for key, amount in {
        "bg1": 0.045, "bg2": 0.09, "sel": 0.18, "text_selection": 0.23,
        "search": 0.30, "focused_search": 0.45, "cursor": 0.75,
    }.items()}
    line_lum, cursor_lum = luminance(colors["bg1"]), luminance(colors["cursor"])
    if (max(line_lum, cursor_lum) + 0.05) / (min(line_lum, cursor_lum) + 0.05) < 4.5:
        colors["cursor"] = readable_on(colors["bg1"])
    return colors


def render_alacritty(palette):
    ui = interaction_colors(palette["bg"])

    def surface(role, foreground="foreground"):
        background = ui[role]
        return {"background": background, foreground: readable_on(background)}

    sections = {
        "colors.primary": {"background": palette["bg"], "foreground": palette["fg2"]},
        "colors.cursor": {"cursor": ui["cursor"], "text": readable_on(ui["cursor"])},
        "colors.vi_mode_cursor": {"cursor": ui["cursor"], "text": readable_on(ui["cursor"])},
        "colors.selection": surface("text_selection", "text"),
        "colors.search.matches": surface("search"),
        "colors.search.focused_match": surface("focused_search"),
        "colors.line_indicator": {"background": ui["bg1"], "foreground": ui["cursor"]},
        "colors.footer_bar": surface("bg2"),
        "colors.hints.start": surface("focused_search"),
        "colors.hints.end": surface("sel"),
    }
    ansi_roles = {"red": "red", "green": "green", "yellow": "yellow",
                  "blue": "blue", "magenta": "purple", "cyan": "teal"}
    for section, black, white in (("normal", "bg2", "fg2"), ("bright", "fg3", "fg")):
        sections[f"colors.{section}"] = {
            "black": palette[black],
            **{name: palette[role] for name, role in ansi_roles.items()},
            "white": palette[white],
        }
    text = "# Generated by apply-theme.sh; use themecolor to change colors.\n"
    for section, values in sections.items():
        text += f"\n[{section}]\n"
        text += "".join(f"{key} = {json.dumps(value)}\n" for key, value in values.items())
    write(CONFIG / "alacritty/theme.toml", text)


def set_background(value, mode):
    if value != "--reset" and not re.fullmatch(r"#?[0-9a-fA-F]{6}", value):
        raise ValueError("颜色必须是六位十六进制，例如 themecolor '#202830'；恢复默认用 --reset")
    defaults = json.loads((THEME / "background-defaults.json").read_text())
    palette_path = THEME / "palette.json"
    palette = json.loads(palette_path.read_text())
    roles = (mode, "nvim_dark") if mode == "dark" else (mode,)
    for role in roles:
        if role not in palette:
            continue
        if value == "--reset":
            palette[role].update(defaults[role])
        else:
            color = "#" + value.lstrip("#").lower()
            base = rgb(defaults[role]["bg"])
            # Preserve the original surface offsets, without accumulating drift.
            for key, original in defaults[role].items():
                channels = [max(0, min(255, new + old - start))
                            for new, old, start in zip(rgb(color), rgb(original), base)]
                palette[role][key] = "#" + "".join(f"{channel:02x}" for channel in channels)
    write(palette_path, json.dumps(palette, indent=2) + "\n")


def update_file(relative, transform):
    path = CONFIG / relative
    if path.is_file():
        write(path, transform(path.read_text()))


def render_surfaces(palette):
    """Update named color roles, so arbitrary/repeated colors never rely on find/replace."""
    roles = {
        ("mode", "normal_alt", "bg"): "bg3",
        ("mode", "select_alt", "bg"): "bg3",
        ("mode", "unset_alt", "bg"): "bg3",
        ("status", "overall", "bg"): "bg2",
        ("status", "progress_normal", "bg"): "bg3",
        ("which", "mask", "bg"): "bg",
        ("which", "separator_style", "fg"): "bg3",
        ("confirm", "btn_yes", "fg"): "bg",
        ("confirm", "btn_no", "bg"): "bg2",
        ("help", "footer", "bg"): "bg2",
    }

    def yazi(text):
        section, result = "", []
        for line in text.splitlines(keepends=True):
            header = re.match(r"\[([^]]+)\]", line)
            if header:
                section = header[1]
            key = re.match(r"(\w+)\s*=", line)
            if key:
                for field in ("fg", "bg"):
                    role = roles.get((section, key[1], field))
                    if role:
                        line = re.sub(rf'(\b{field}\s*=\s*)"[^"]*"',
                                      lambda m: m[1] + '"' + palette[role] + '"', line)
            result.append(line)
        return "".join(result)

    update_file("yazi/theme.toml", yazi)
    update_file("cava/config", lambda text: re.sub(
        r"(?m)^(background\s*=\s*)['\"][^'\"]*['\"]",
        lambda m: m[1] + "'" + palette["bg"] + "'", text))
    update_file("cava/config", lambda text: re.sub(
        r"(?m)^(gradient_color_1\s*=\s*)['\"][^'\"]*['\"]",
        lambda m: m[1] + "'" + palette["bg3"] + "'", text))
    for key, role in (("background", "bg"), ("lineHighlight", "bg2")):
        update_file("silicon/themes/obsidian-ember.tmTheme", lambda text: re.sub(
            rf"(<key>{key}</key>\s*<string>)[^<]*(</string>)",
            lambda m: m[1] + palette[role] + m[2], text))
    zathura_roles = {
        "default-bg": "bg", "statusbar-bg": "bg1", "inputbar-bg": "bg2",
        "notification-bg": "bg2", "completion-bg": "bg1",
        "notification-error-fg": "bg", "notification-warning-fg": "bg",
        "completion-highlight-fg": "bg", "recolor-lightcolor": "bg",
    }
    for key, role in zathura_roles.items():
        update_file("zathura/zathurarc", lambda text: re.sub(
            rf'(?m)^(set\s+{key}\s+)"[^"]*"',
            lambda m: m[1] + '"' + palette[role] + '"', text))


def zen_profiles():
    found = set()
    for root in (CONFIG / "zen", Path.home() / ".zen"):
        ini = configparser.ConfigParser(interpolation=None)
        ini.read(root / "profiles.ini")
        for section in ini.sections():
            if not section.startswith("Profile") or not ini.has_option(section, "Path"):
                continue
            path = Path(ini[section]["Path"])
            if ini[section].get("IsRelative", "1") == "1":
                path = root / path
            path = path.resolve()
            if path.is_dir() and path not in found:
                found.add(path)
                yield path


def add_import(path, name):
    text = path.read_text() if path.exists() else ""
    declaration = f'@import url("{name}");'
    if declaration in text:
        return
    charset = re.match(r'^\ufeff?@charset\s+"[^"]+";\s*', text)
    position = charset.end() if charset else 0
    write(path, text[:position] + declaration + "\n" + text[position:])


def render_zen(palette, mode):
    variables = "\n".join(f"  --system-theme-{key}: {palette[key]};"
                          for key in ("bg", "bg1", "bg2", "bg3", "fg", "fg2"))
    chrome = """/* Generated by apply-theme.sh; use themecolor to change colors. */
:root {
VARIABLES
  color-scheme: MODE !important;
  --zen-colors-tertiary: var(--system-theme-bg) !important;
  --zen-colors-secondary: var(--system-theme-bg2) !important;
  --zen-colors-border: var(--system-theme-bg3) !important;
  --zen-colors-input-bg: var(--system-theme-bg1) !important;
  --zen-dialog-background: var(--system-theme-bg1) !important;
  --zen-urlbar-background: var(--system-theme-bg1) !important;
  --zen-themed-toolbar-bg: var(--system-theme-bg) !important;
  --zen-themed-toolbar-bg-transparent: var(--system-theme-bg) !important;
  --zen-navigator-toolbox-background: var(--system-theme-bg) !important;
  --toolbar-bgcolor: var(--system-theme-bg) !important;
  --toolbar-field-background-color: var(--system-theme-bg1) !important;
  --toolbar-field-focus-background-color: var(--system-theme-bg1) !important;
  --toolbar-color: var(--system-theme-fg2) !important;
  --toolbar-field-color: var(--system-theme-fg) !important;
  --toolbar-field-focus-color: var(--system-theme-fg) !important;
  --toolbox-textcolor: var(--system-theme-fg2) !important;
  --lwt-text-color: var(--system-theme-fg2) !important;
  --lwt-toolbar-field-color: var(--system-theme-fg) !important;
  --sidebar-background-color: var(--system-theme-bg) !important;
  --sidebar-text-color: var(--system-theme-fg2) !important;
  --arrowpanel-background: var(--system-theme-bg1) !important;
  --arrowpanel-color: var(--system-theme-fg) !important;
}
/* New Zen versions set these variables directly on background elements. */
:root, .zen-browser-generic-background {
  --zen-main-browser-background: var(--system-theme-bg) !important;
  --zen-main-browser-background-toolbar: var(--system-theme-bg) !important;
  --zen-main-browser-background-old: var(--system-theme-bg) !important;
  --zen-main-browser-background-toolbar-old: var(--system-theme-bg) !important;
}
.zen-browser-generic-background .zen-browser-grain { display: none !important; }
#zen-main-app-wrapper { background: var(--system-theme-bg) !important; }
""".replace("VARIABLES", variables).replace("MODE", mode)
    content = """/* Generated by apply-theme.sh. Only browser-owned pages are styled. */
@-moz-document url("about:newtab"), url("about:home"), url("about:blank") {
  :root {
VARIABLES
    color-scheme: MODE !important;
    --newtab-background-color: var(--system-theme-bg) !important;
    --newtab-background-color-secondary: var(--system-theme-bg1) !important;
    --newtab-text-primary-color: var(--system-theme-fg) !important;
    --newtab-text-secondary-color: var(--system-theme-fg2) !important;
    --zen-main-browser-background: var(--system-theme-bg) !important;
  }
  html, body {
    background: var(--system-theme-bg) !important;
    color: var(--system-theme-fg2) !important;
  }
}
""".replace("VARIABLES", variables).replace("MODE", mode)
    count = 0
    for profile in zen_profiles():
        directory = profile / "chrome"
        write(directory / "system-theme-chrome.css", chrome)
        write(directory / "system-theme-content.css", content)
        add_import(directory / "userChrome.css", "system-theme-chrome.css")
        add_import(directory / "userContent.css", "system-theme-content.css")
        user_js = profile / "user.js"
        text = user_js.read_text() if user_js.exists() else ""
        # Never edit prefs.js while the browser is running; user.js is read on startup.
        preference = "toolkit.legacyUserProfileCustomizations.stylesheets"
        text = re.sub(r'(?m)^\s*user_pref\("' + re.escape(preference)
                      + r'",[^\n]*\);[^\n]*\n?', "", text)
        write(user_js, text.rstrip() + f'\nuser_pref("{preference}", true);\n')
        count += 1
    return count


def main():
    action = sys.argv[1]
    mode = current_mode()
    if action == "set":
        set_background(sys.argv[2], sys.argv[3])
    elif action == "show":
        print(json.loads((THEME / "palette.json").read_text())[mode]["bg"])
    elif action == "alacritty":
        render_alacritty(json.loads((THEME / "palette.json").read_text())[sys.argv[2]])
    elif action == "render":
        mode = sys.argv[2]
        palette = json.loads((THEME / "palette.json").read_text())[mode]
        render_surfaces(palette)
        count = render_zen(palette, mode)
        if count:
            print(f"Zen：已更新 {count} 个配置档案，重启浏览器后生效。")
    else:
        raise ValueError(f"Unknown action: {action}")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, configparser.Error) as error:
        print(f"themecolor: {error}", file=sys.stderr)
        sys.exit(2)
